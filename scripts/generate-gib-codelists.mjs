// Writes src/gib-codelists.ts from GİB's e-Fatura code list (UBL-TR_Codelist.xml in the `schematron` folder of
// GİB's e-Fatura package). Run it again when GİB publishes a new package:
//   node scripts/generate-gib-codelists.mjs /path/to/e-FaturaPaketi/schematron/UBL-TR_Codelist.xml 2026-08-21
import { readFileSync, writeFileSync } from 'fs';

const [source, packageDate] = process.argv.slice(2);
if (!source || !/^\d{4}-\d{2}-\d{2}$/.test(packageDate ?? '')) {
  console.error(
    'usage: node scripts/generate-gib-codelists.mjs <UBL-TR_Codelist.xml> <package date YYYY-MM-DD>',
  );
  process.exit(1);
}

// [exported name, GİB list name, what it is]
const LISTS = [
  ['GIB_EFATURA_PROFILE_IDS', 'ProfileIDType', 'Profiles of an e-Fatura (cbc:ProfileID).'],
  ['GIB_EARCHIVE_PROFILE_IDS', 'ProfileIDTypeEarchive', 'Profiles of an e-Arşiv invoice.'],
  ['GIB_INVOICE_TYPE_CODES', 'InvoiceTypeCodeList', 'Invoice types (cbc:InvoiceTypeCode).'],
  ['CURRENCY_CODES', 'CurrencyCodeList', 'Currency codes (ISO 4217).'],
  ['COUNTRY_CODES', 'CountryCodeList', "Country codes, as a tourist's nationality."],
  [
    'PARTY_IDENTIFICATION_SCHEMES',
    'PartyIdentificationIDType',
    'schemeID values of a party identification.',
  ],
  ['TAX_TYPE_CODES', 'TaxType', 'Tax type codes (cbc:TaxTypeCode) of TaxTotal.'],
  ['TAX_EXEMPTION_REASON_CODES', 'TaxExemptionReasonCodeType', 'VAT exemption reason codes.'],
  [
    'EXEMPTION_CODES_FOR_ISTISNA',
    'istisnaTaxExemptionReasonCodeType',
    'Exemption codes an ISTISNA type uses.',
  ],
  [
    'EXEMPTION_CODES_FOR_OZELMATRAH',
    'ozelMatrahTaxExemptionReasonCodeType',
    'Exemption codes an OZELMATRAH type uses.',
  ],
  [
    'EXEMPTION_CODES_FOR_IHRACKAYITLI',
    'ihracExemptionReasonCodeType',
    'Exemption codes an IHRACKAYITLI type uses.',
  ],
  [
    'PAYMENT_MEANS_CODES',
    'PaymentMeansCodeTypeList',
    'Payment means codes (cbc:PaymentMeansCode).',
  ],
  ['DELIVERY_TERM_CODES', 'DeliveryTermCodeList', 'Delivery terms (INCOTERMS).'],
  ['TRANSPORT_MODE_CODES', 'TransportModeCodeList', 'Transport mode codes.'],
  ['PACKAGE_TYPE_CODES', 'PackageTypeCodeList', 'Package type codes (cbc:PackagingTypeCode).'],
  [
    'WITHHOLDING_TAX_TYPE_CODES',
    'WithholdingTaxType',
    'KDV tevkifat codes (WithholdingTaxTotal TaxTypeCode).',
  ],
  [
    'WITHHOLDING_CODE_PERCENTS',
    'WithholdingTaxTypeWithPercent',
    'Withholding code followed by its percent (60690 is 606 at 90).',
  ],
];

const xml = readFileSync(source, 'utf8');
const out = [
  `// Generated by scripts/generate-gib-codelists.mjs from GİB's e-Fatura code list (package of ${packageDate}).`,
  '// Do not edit by hand: run the script on a newer package instead.',
  '',
  `/** Date of GİB's e-Fatura package these lists come from. */`,
  `export const GIB_CODELIST_DATE = '${packageDate}';`,
];
for (const [name, gibName, doc] of LISTS) {
  const match = xml.match(new RegExp(`name="${gibName}"\\s+value="([^"]*)"`));
  if (!match) throw new Error(`${gibName} not found in ${source}`);
  const codes = match[1]
    .split(',')
    .map((code) => code.replace(/'/g, '').trim())
    .filter(Boolean);
  const lines = [];
  for (const code of codes.map((c) => `'${c}',`)) {
    if (lines.length && lines[lines.length - 1].length + code.length < 100)
      lines[lines.length - 1] += ` ${code}`;
    else lines.push(`  ${code}`);
  }
  out.push(
    '',
    `/** ${doc} GİB's \`${gibName}\`. */`,
    `export const ${name}: readonly string[] = [`,
    ...lines,
    '];',
  );
}
writeFileSync(new URL('../src/gib-codelists.ts', import.meta.url), `${out.join('\n')}\n`);
console.log(`src/gib-codelists.ts: ${LISTS.length} lists`);
